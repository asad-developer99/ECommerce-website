export const getProductById = (id: string): Product | undefined =>
  products.find((p) => p.id === id);

export const getRelatedProducts = (product: Product, count = 4): Product[] =>
  products
    .filter((p) => p.id !== product.id && (p.category === product.category || p.gender === product.gender))
    .slice(0, count);

export const getNewArrivals = (): Product[] => products.filter((p) => p.isNew);
export const getBestSellers = (): Product[] => products.filter((p) => p.bestSeller);
export const getOnSale = (): Product[] => products.filter((p) => p.onSale);
export const getByCategory = (cat: string): Product[] =>
  products.filter((p) => p.category === cat || p.gender === cat);

